#!/usr/bin/env python3
"""Generate both sites' local theme assets from Notes/Theme/css.

Run from any directory; --check verifies output without writing files.
Palette values belong in Notes, web role mappings and behavior beside this file.
"""
import argparse
import json
import re
from pathlib import Path

SOURCE = Path(__file__).resolve().parent
WORKSPACE = SOURCE.parents[2]
PALETTE = WORKSPACE / 'Notes/Theme/css'
SITES = (SOURCE.parent, WORKSPACE / 'Web/web-poortjie')
SCHEMES = {
    'light': ':root, html.light',
    'dark': 'html.dark',
    'light-mc': 'html[data-contrast="medium"]:not(.dark)',
    'dark-mc': 'html.dark[data-contrast="medium"]',
    'light-hc': 'html[data-contrast="high"]:not(.dark)',
    'dark-hc': 'html.dark[data-contrast="high"]',
}
HEADER = '/* Generated by theme-source/generate-theme.py. Do not edit. */\n'


def palette_css():
    blocks = []
    palettes = {}
    for name, selector in SCHEMES.items():
        tokens = dict(re.findall(r'--md-sys-color-([\w-]+):\s*rgb\((\d+ \d+ \d+)\);',
                                 (PALETTE / (name + '.css')).read_text()))
        if not tokens or (palettes and tokens.keys() != palettes['light'].keys()):
            raise ValueError('Missing or inconsistent palette roles: ' + name)
        palettes[name] = tokens
        declarations = [f'  --md-sys-color-{role}: rgb({rgb});\n'
                        f'  --md-sys-color-{role}-rgb: {rgb};' for role, rgb in tokens.items()]
        declarations.append('  color-scheme: ' + ('dark' if name.startswith('dark') else 'light') + ';')
        blocks.append(selector + ' {\n' + '\n'.join(declarations) + '\n}')
    return '\n\n'.join(blocks), palettes


def outputs():
    palette, schemes = palette_css()
    scheme_json = json.dumps(schemes, separators=(',', ':'))
    assets = {
        'styles/digilayn-theme.css': HEADER + palette + '\n\n' + (SOURCE / 'theme.css').read_text(),
        'scripts/theme.js': HEADER + (SOURCE / 'theme.js').read_text().replace('/* PALETTE_SCHEMES */ {}', scheme_json),
        'scripts/digilayn-tailwind.js': HEADER + (SOURCE / 'tailwind.js').read_text(),
    }
    result = {}
    for site in SITES:
        for name, content in assets.items():
            result[site / name] = content
        manifest_path = site / 'favicon/site.webmanifest'
        manifest = json.loads(manifest_path.read_text())
        to_hex = lambda value: '#' + ''.join(f'{int(channel):02x}' for channel in value.split())
        manifest['theme_color'] = to_hex(schemes['light']['primary-container'])
        manifest['background_color'] = to_hex(schemes['light']['background'])
        result[manifest_path] = json.dumps(manifest, indent=2) + '\n'
    return result


def check_consumers():
    """Keep palette literals and colour-scale utilities out of feature code."""
    issues = []
    literal = re.compile(r'(?<![&\w])#[\da-fA-F]{3,8}\b|rgba?\(\s*\d')
    utility = re.compile(r'\b(?:bg|text|border(?:-[trblxyse])?|ring|from|via|to|shadow)-'
                         r'(?:slate|gray|green|emerald|blue|indigo|purple|amber|yellow|red)-\d+')
    google_logo = {'#4285F4', '#34A853', '#FBBC05', '#EA4335'}
    for site in SITES:
        for path in site.rglob('*'):
            if path.suffix not in {'.html', '.css', '.js'} or any(
                    name in path.parts for name in {'tests', 'theme-source', '.git'}):
                continue
            if path.name in {'digilayn-theme.css', 'theme.js'}:
                continue
            # Image-upload flattening uses a fixed white photographic background.
            if path == site / 'scripts/image-upload.js':
                continue
            for number, line in enumerate(path.read_text().splitlines(), 1):
                values = literal.findall(line)
                if path.parent.name == 'authentication' and path.name in {'login.html', 'register.html'}:
                    values = [value for value in values if value not in google_logo]
                if values or utility.search(line):
                    issues.append(f'{path.relative_to(WORKSPACE)}:{number}: local colour definition')
    return issues


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(WORKSPACE)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit('Theme assets need regeneration:\n' + '\n'.join(stale))
    if args.check:
        issues = check_consumers()
        if issues:
            raise SystemExit('Use shared theme roles instead:\n' + '\n'.join(issues))
    print('Theme assets match Notes palette.' if args.check else 'Generated theme assets for both websites.')


if __name__ == '__main__':
    main()
